def main() -> None:
    p = argparse.ArgumentParser(description="Merge hand-written aliases into the graphs")
    p.add_argument("--check", action="store_true", help="report only, write nothing")
    args = p.parse_args()

    for subject, table in ALIASES.items():
        path = GRAPHS[subject]
        graph = json.loads(path.read_text(encoding="utf-8"))
        concepts = graph["concepts"]

        unknown = [s for s in table if s not in concepts]
        if unknown:
            raise SystemExit(f"{subject}: these slugs are not in the graph: {unknown}")

        added = 0
        for slug, aliases in table.items():
            if concepts[slug].get("aliases") != aliases:
                added += 1
            if not args.check:
                concepts[slug]["aliases"] = aliases

        have = sum(1 for c in concepts.values() if c.get("aliases"))
        print(f"{subject}: {added} concepts updated, "
              f"{have + (0 if not args.check else added)}/{len(concepts)} now have aliases")
        if not args.check:
            path.write_text(json.dumps(graph, indent=2, ensure_ascii=False) + "\n",
                            encoding="utf-8")
            print(f"  written {path.relative_to(BASE).as_posix()}")


if __name__ == "__main__":
    main()
